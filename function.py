def add_two_number(first_number, second_number):
    sum_of_number = first_number + second_number
    return sum_of_number
    
def exponential_of_number(number,power):
    return number **power
    
def division_of_number(first_number,second_number):
    divide_of_number =  first_number / second_number
    return divide_of_number
      
    
def multiply_of_number(first_number, second_number):
    product_of_number  = first_number * second_number
    return product_of_number
    
def subtraction_of_number(first_number, second_number):
    minus_of_number = first_number - second_number
    return minus_of_number
    
        
